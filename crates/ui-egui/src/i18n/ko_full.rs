//! Korean effect and fixed panel display strings. IDs and stored project names stay English.
//! EffectCraft registry names are translated from their meaning; no proprietary resources used.
use std::collections::HashMap;
use std::sync::OnceLock;
pub(super) fn lookup(text: &str) -> Option<&'static str> {
    static INDEX: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    INDEX.get_or_init(|| ROWS.iter().copied().collect()).get(text).copied()
}
/// Keep renamed effects verbatim, including names that happen to be other UI labels.
pub(crate) fn effect_group(id: &str, stored: &str) -> String {
    if super::ui::current() != "ko" {
        return stored.into();
    }
    let Some(spec) = effectcraft_engine::effects::find(id) else {
        return stored.into();
    };
    let translated = lookup(spec.name).unwrap_or(spec.name);
    if stored == spec.name {
        return translated.into();
    }
    if let Some(suffix) = stored.strip_prefix(spec.name).and_then(|s| s.strip_prefix(' '))
        && !suffix.is_empty()
        && suffix.bytes().all(|b| b.is_ascii_digit())
    {
        return format!("{translated} {suffix}");
    }
    stored.into()
}
